-- Baseline for the recorded PostgreSQL 18.3 public schema.
-- Flyway is disabled by default until this baseline is rehearsed and existing
-- databases are verified and explicitly baselined.

CREATE TABLE public.alerts (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.alerts_id_seq
        START WITH 1
        INCREMENT BY 1
        CACHE 1
    ),
    alert_id varchar(255) NOT NULL,
    description text,
    host varchar(255),
    rule varchar(255) NOT NULL,
    severity varchar(255) NOT NULL,
    source varchar(255) NOT NULL,
    timestamp timestamp(6) without time zone,
    CONSTRAINT pk_alerts PRIMARY KEY (id),
    CONSTRAINT uq_alerts_alert_id UNIQUE (alert_id)
);

CREATE TABLE public.incidents (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.incidents_id_seq
        START WITH 1
        INCREMENT BY 1
        CACHE 1
    ),
    detection varchar(255),
    host varchar(255),
    incident_id varchar(255) NOT NULL,
    severity varchar(255) NOT NULL,
    status varchar(255) NOT NULL,
    timestamp timestamp(6) without time zone,
    title varchar(255) NOT NULL,
    CONSTRAINT pk_incidents PRIMARY KEY (id),
    CONSTRAINT uq_incidents_incident_id UNIQUE (incident_id)
);

CREATE TABLE public.ai_investigations (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.ai_investigations_id_seq
        START WITH 1
        INCREMENT BY 1
        CACHE 1
    ),
    approval_required boolean NOT NULL,
    attack_technique varchar(255),
    classification varchar(255) NOT NULL,
    confidence double precision NOT NULL,
    recommended_action varchar(255),
    risk varchar(255),
    severity varchar(255) NOT NULL,
    summary text,
    incident_pk bigint NOT NULL,
    CONSTRAINT pk_ai_investigations PRIMARY KEY (id),
    CONSTRAINT uq_ai_investigations_incident_pk UNIQUE (incident_pk),
    CONSTRAINT fk_ai_investigations_incident
        FOREIGN KEY (incident_pk) REFERENCES public.incidents (id)
);

CREATE TABLE public.ai_investigation_evidence (
    investigation_id bigint NOT NULL,
    evidence text NOT NULL,
    position integer NOT NULL,
    CONSTRAINT pk_ai_investigation_evidence
        PRIMARY KEY (investigation_id, position),
    CONSTRAINT fk_ai_investigation_evidence_investigation
        FOREIGN KEY (investigation_id)
        REFERENCES public.ai_investigations (id)
);
