-- Additive schema for persisted approval decisions and investigation provenance.
-- The current application has no authentication; actor_id intentionally remains NULL
-- until a real authenticated principal is integrated.

ALTER TABLE public.ai_investigations
    ADD COLUMN analysis_status varchar(24) NOT NULL DEFAULT 'UNKNOWN',
    ADD COLUMN scenario_id varchar(64) NULL,
    ADD CONSTRAINT ck_ai_investigations_analysis_status
        CHECK (analysis_status IN ('SIMULATED', 'MODEL_GENERATED', 'UNKNOWN'));

CREATE TABLE public.incident_approval_decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_pk bigint NOT NULL,
    decision varchar(8) NOT NULL,
    decided_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_id varchar(255) NULL,
    CONSTRAINT ck_incident_approval_decisions_decision
        CHECK (decision IN ('APPROVED', 'DENIED')),
    CONSTRAINT fk_incident_approval_decisions_incident
        FOREIGN KEY (incident_pk) REFERENCES public.incidents (id)
);

CREATE INDEX ix_incident_approval_decisions_incident_time
    ON public.incident_approval_decisions (incident_pk, decided_at DESC, id DESC);
